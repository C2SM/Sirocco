#!/usr/local/bin/bash

# Environment common to all PEs
# =============================
santis_common_environment(){
    ulimit -s unlimited
    ulimit -c 0

    # Libfabric / Slingshot
    # ---------------------
    export FI_PROVIDER=cxi
    export FI_LOG_LEVEL=warn
    export FI_CXI_RX_MATCH_MODE=software
    export MPICH_OFI_CXI_COUNTER_REPORT=3

    # OpenMP
    # ------
    export OMP_NUM_THREADS=1
    export ICON_THREADS=1
    export OMP_SCHEDULE=guided,16
    export OMP_DYNAMIC="false"
    export OMP_STACKSIZE=200M

    # NVHPC
    # ----
    export NVCOMPILER_TERM=trace

    # Python tracebacks of the embedded ICON4Py interpreter on fatal signals (used by the hang watchdog)
    export PYTHONFAULTHANDLER=1
}

# Compute cpu environment
# =======================
santis_compute_cpu_environment(){
    # MPICH
    # -----
    if [ "${SIROCCO_TARGET}" == "hybrid" ]; then
        export MPICH_GPU_SUPPORT_ENABLED=1
        export MPICH_GPU_IPC_ENABLED=1
        # GPU-aware MPICH requires a visible device, take the one of the local NUMA node
        export CUDA_VISIBLE_DEVICES=$numa_node
    else
        export MPICH_GPU_SUPPORT_ENABLED=0
        export MPICH_GPU_IPC_ENABLED=0
    fi
    export MPICH_OFI_NIC_POLICY=NUMA
}

# Compute gpu environment
# =======================
santis_compute_gpu_environment(){
    # MPICH
    # -----
    export MPICH_GPU_SUPPORT_ENABLED=1
    export MPICH_GPU_IPC_ENABLED=1
    export MPICH_OFI_NIC_POLICY=GPU

    # CUDA
    # ----
    export CUDA_VISIBLE_DEVICES=$numa_node
    export CUDA_BUFFER_PAGE_IN_THRESHOLD_MS=0.001

    # NVHPC
    # -----
    export NVCOMPILER_ACC_SYNCHRONOUS=0
    export NVCOMPILER_ACC_DEFER_UPLOADS=1
    export NVCOMPILER_ACC_USE_GRAPH=1  # Harmless if cuda-graphs is disabled
    export NVCOMPILER_ACC_NOTIFY=0
}

# icon4py environment
# ===================
santis_icon4py_environment(){
    # run.env is generated by the ICON configure step and puts the ICON4Py venv on PATH
    source "$(dirname "${ICON4PY_VENV}")/run.env"
    # run.env points CXX and CUDAHOSTCXX to the Spack compiler wrapper, which refuses to run
    # outside a Spack build and breaks the GT4Py/DaCe JIT. Use the compilers of the uenv view.
    export CXX="$(command -v mpicxx)"
    # nvcc's host compiler must match the one DaCe uses for the CPU objects
    export CUDAHOSTCXX="$(command -v g++)"
    # nvc++ rejects "#pragma omp declare reduction" in dace/types.h, compile host objects with g++
    export DACE_compiler_cpu_executable="$(command -v g++)"
    export DACE_compiler_cpu_args='-Wall -Wextra -march=native -Wno-unused-parameter'
    export DACE_compiler_cuda_block_size_limit=256

    export CUDAARCHS=90
    export PYTHONOPTIMIZE=2
    export CUPY_CACHE_IN_MEMORY=1
    export GT4PY_BUILD_CACHE_LIFETIME=persistent
    export GT4PY_UNSTRUCTURED_HORIZONTAL_HAS_UNIT_STRIDE=1
    export ICON4PY_WAIT_FOR_COMPILATION=1
    export PY2FGEN_LOG_LEVEL=WARNING

    export PMI_MMAP_SYNC_WAIT_TIME=300
    export HWMALLOC_LARGE_LIMIT=$((1 << 26)) # 64 MiB, default 2 MiB
    export HWMALLOC_LARGE_SEGMENT_SIZE=$((1 << 26)) # 64 MiB, default 2 MiB
    export HWMALLOC_NEVER_FREE=1
    export MPICH_GPU_IPC_CACHE_MAX_SIZE=100

    # Node-local temporary directory: nvcc temporary file names collide between nodes on a shared file system
    export TMPDIR="/dev/shm/gt4py_tmp_${SLURM_JOB_ID}"
    mkdir -p "${TMPDIR}"
}

# IO environment
# ==============
santis_io_environment(){
    # MPICH
    # -----
    if [ "${SIROCCO_TARGET}" == "cpu" ]; then
        export MPICH_GPU_SUPPORT_ENABLED=0
        export MPICH_GPU_IPC_ENABLED=0
    else
        export MPICH_GPU_SUPPORT_ENABLED=1
        export MPICH_GPU_IPC_ENABLED=1
        export CUDA_VISIBLE_DEVICES=$numa_node
    fi
    export MPICH_OFI_NIC_POLICY=NUMA
}
